namespace PostalApp
{
    /// <summary>
    /// Уровни логирования.
    /// Определяют важность сообщения.
    /// </summary>
    public enum LogLevel
    {
        /// <summary>
        /// Отладочная информация (только для разработки).
        /// Используй для: детальной информации о работе приложения, значений переменных.
        /// Пример: "Загружено маркеров: 150", "Пользователь нажал кнопку X"
        /// </summary>
        Debug = 0,

        /// <summary>
        /// Информационные сообщения о нормальной работе.
        /// Используй для: успешных операций, важных событий.
        /// Пример: "Пользователь вошел в систему", "Данные успешно сохранены"
        /// </summary>
        Info = 1,

        /// <summary>
        /// Предупреждения о потенциальных проблемах.
        /// Используй для: некритичных проблем, которые не мешают работе.
        /// Пример: "Некоторые поля не заполнены", "Медленное подключение к БД"
        /// </summary>
        Warning = 2,

        /// <summary>
        /// Ошибки, которые не приводят к падению приложения.
        /// Используй для: обработанных исключений, неудачных операций.
        /// Пример: "Не удалось загрузить маркеры", "Ошибка сохранения данных"
        /// </summary>
        Error = 3,

        /// <summary>
        /// Критические ошибки, которые могут привести к падению приложения.
        /// Используй для: необработанных исключений, потери соединения с БД.
        /// Пример: "Потеряно соединение с сервером", "Критическая ошибка инициализации"
        /// </summary>
        Critical = 4
    }
}
